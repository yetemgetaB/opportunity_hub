import type { Opportunity } from '../types/student'

type OpportunitySeed = Pick<Opportunity, 'id' | 'company' | 'title' | 'type' | 'location' | 'deadline' | 'tags' | 'fieldsOfStudy'> & {
  organizationId: string
  remote?: boolean
  compensation?: string
  description: string
  status?: 'DRAFT' | 'PUBLISHED'
}

function buildOpportunity(seed: OpportunitySeed, fit: number): Opportunity {
  return {
    ...seed,
    tagline: `${seed.company} creates practical opportunities for emerging talent.`,
    description: seed.description,
    overview: seed.description,
    requirements: [
      `Currently studying or recently graduated in ${seed.fieldsOfStudy?.join(', ') ?? 'a relevant field'}.`,
      `Interest in ${seed.tags.slice(0, 2).join(' and ')} and a willingness to learn.`,
      'Strong communication, collaboration, and problem-solving skills.',
    ],
    benefits: [
      seed.compensation ?? 'Mentorship and practical project experience.',
      'A supportive team environment with regular feedback.',
      'An opportunity to build work-ready skills.',
    ],
    fit,
    matchBreakdown: [
      { label: 'Skills alignment', value: Math.max(60, fit - 2) },
      { label: 'Study field', value: Math.max(60, fit - 5) },
      { label: 'Experience fit', value: Math.max(60, fit - 8) },
    ],
    recommended: fit >= 85,
    organizationId: seed.organizationId,
    status: seed.status ?? 'PUBLISHED',
    isRemote: seed.remote ?? /remote/i.test(seed.location),
    eligibleFields: seed.fieldsOfStudy,
    minimumAcademicYear: 2,
    maximumAcademicYear: 5,
    minimumGpa: 2.5,
    compensation: seed.compensation ?? null,
    applicationUrl: null,
    createdAt: '2026-09-15T09:00:00.000Z',
    publishedAt: '2026-09-18T09:00:00.000Z',
  }
}

